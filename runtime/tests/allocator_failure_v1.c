    assert(yaza_arena_v1_leave(&list_create_context) == 1);
    assert(yaza_arena_v1_destroy(list_create_arena) == 1);

    YazaArenaV1 *system_failure_list_arena = yaza_arena_v1_create(64ULL * 1024ULL);
