    assert(cycle_metrics.allocation_failures == 1);
    assert(cycle_metrics.retained_reserved_bytes == 64ULL * 1024ULL);

    assert(yaza_arena_v1_scope_begin(request_arena, &request_context) == 1);
    yaza_rt_v1_test_fail_alloc_after(0);
