    assert(yaza_arena_v1_reserved(system_failure_list_arena) == 0);
    assert(yaza_rt_v1_arena_allocation_failures() == list_failures_before + 1);
    assert(yaza_arena_v1_leave(&system_failure_list_context) == 1);
